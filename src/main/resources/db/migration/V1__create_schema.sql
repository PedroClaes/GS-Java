-- =====================================================================
-- V1 - Schema da API Java do Conserta Ai
--
-- A API Java e dona dos usuarios e das ocorrencias. A API .NET guarda
-- apenas os ids (sem chave estrangeira entre bancos) e avisa pelo
-- RabbitMQ quando o total de apoios de uma ocorrencia muda.
-- =====================================================================

CREATE TABLE usuarios (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(100) NOT NULL,
    email       VARCHAR(150) NOT NULL,
    senha_hash  VARCHAR(100) NOT NULL,
    papel       VARCHAR(20)  NOT NULL,
    bairro      VARCHAR(80),
    criado_em   TIMESTAMP    NOT NULL,

    CONSTRAINT uk_usuarios_email UNIQUE (email),
    CONSTRAINT ck_usuarios_papel CHECK (papel IN ('CIDADAO', 'GESTOR'))
);

CREATE TABLE categorias (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome               VARCHAR(60)  NOT NULL,
    descricao          VARCHAR(255),
    orgao_responsavel  VARCHAR(120) NOT NULL,
    prazo_sla_dias     INTEGER      NOT NULL,
    ativa              BOOLEAN      NOT NULL DEFAULT TRUE,

    CONSTRAINT uk_categorias_nome UNIQUE (nome),
    CONSTRAINT ck_categorias_prazo CHECK (prazo_sla_dias > 0)
);

CREATE TABLE ocorrencias (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo                  VARCHAR(120)  NOT NULL,
    descricao               VARCHAR(1000) NOT NULL,
    endereco                VARCHAR(200)  NOT NULL,
    bairro                  VARCHAR(80)   NOT NULL,
    latitude                NUMERIC(9,6),
    longitude               NUMERIC(9,6),
    status                  VARCHAR(20)   NOT NULL,

    -- Resultado da triagem (IA ou regras de fallback)
    categoria_id            BIGINT,
    urgencia                VARCHAR(10),
    risco_imediato          BOOLEAN       NOT NULL DEFAULT FALSE,
    resumo_ia               VARCHAR(500),
    orgao_sugerido          VARCHAR(120),
    origem_triagem          VARCHAR(10),
    possivel_duplicada_de   BIGINT,
    triada_em               TIMESTAMP,

    -- Participacao (atualizada pelos eventos da API .NET) e fila do gestor
    qtd_apoios              INTEGER       NOT NULL DEFAULT 0,
    ultimo_evento_apoio_em  TIMESTAMP,
    prioridade              INTEGER       NOT NULL DEFAULT 0,

    autor_id                BIGINT        NOT NULL,
    criado_em               TIMESTAMP     NOT NULL,
    atualizado_em           TIMESTAMP     NOT NULL,

    CONSTRAINT fk_ocorrencias_categoria FOREIGN KEY (categoria_id) REFERENCES categorias (id),
    CONSTRAINT fk_ocorrencias_autor     FOREIGN KEY (autor_id)     REFERENCES usuarios (id),
    CONSTRAINT fk_ocorrencias_duplicada FOREIGN KEY (possivel_duplicada_de)
        REFERENCES ocorrencias (id) ON DELETE SET NULL,
    CONSTRAINT ck_ocorrencias_status CHECK (
        status IN ('EM_TRIAGEM', 'ABERTA', 'EM_ANDAMENTO', 'RESOLVIDA', 'CANCELADA')),
    CONSTRAINT ck_ocorrencias_urgencia CHECK (
        urgencia IS NULL OR urgencia IN ('BAIXA', 'MEDIA', 'ALTA', 'CRITICA')),
    CONSTRAINT ck_ocorrencias_origem CHECK (
        origem_triagem IS NULL OR origem_triagem IN ('IA', 'REGRAS')),
    CONSTRAINT ck_ocorrencias_apoios CHECK (qtd_apoios >= 0),
    CONSTRAINT ck_ocorrencias_prioridade CHECK (prioridade BETWEEN 0 AND 100)
);

-- Fila do gestor: ocorrencias em aberto ordenadas pela prioridade
CREATE INDEX idx_ocorrencias_fila   ON ocorrencias (status, prioridade DESC);
-- Busca de candidatas a duplicada (mesmo bairro, em aberto)
CREATE INDEX idx_ocorrencias_bairro ON ocorrencias (bairro, status);
CREATE INDEX idx_ocorrencias_autor  ON ocorrencias (autor_id, criado_em DESC);

CREATE TABLE historico_status (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ocorrencia_id    BIGINT       NOT NULL,
    status_anterior  VARCHAR(20),
    status_novo      VARCHAR(20)  NOT NULL,
    observacao       VARCHAR(500),
    -- Nulo quando a mudanca foi feita pelo sistema (ex.: fim da triagem)
    responsavel_id   BIGINT,
    data             TIMESTAMP    NOT NULL,

    CONSTRAINT fk_historico_ocorrencia  FOREIGN KEY (ocorrencia_id)
        REFERENCES ocorrencias (id) ON DELETE CASCADE,
    CONSTRAINT fk_historico_responsavel FOREIGN KEY (responsavel_id) REFERENCES usuarios (id)
);

CREATE INDEX idx_historico_ocorrencia ON historico_status (ocorrencia_id, data);
